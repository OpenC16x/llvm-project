#ifndef LLVM_LIB_TARGET_C166_MCTARGETDESC_C166INSTPRINTER_H
#define LLVM_LIB_TARGET_C166_MCTARGETDESC_C166INSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"

namespace llvm {

class C166InstPrinter : public MCInstPrinter {
public:
  C166InstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  void printRegName(raw_ostream &O, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  // Autogenerated by tblgen.
  std::pair<const char *, uint64_t> getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemRIOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printAddr16Operand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBrTargetOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCallTargetOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCoPtrOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCoIdxOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printCCOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printRelTargetOperand(const MCInst *MI, uint64_t Address, unsigned OpNo,
                             raw_ostream &O);
  void printMemROperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemRPostIncOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBitOffOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printMemRPreDecOperand(const MCInst *MI, unsigned OpNo,
                              raw_ostream &O);
  void printBitPosOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBitAddrOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
};

} // namespace llvm

#endif
