#ifndef LLVM_LIB_TARGET_C166_C166SUBTARGET_H
#define LLVM_LIB_TARGET_C166_C166SUBTARGET_H

#include "C166FrameLowering.h"
#include "C166ISelLowering.h"
#include "C166InstrInfo.h"
#include "llvm/CodeGen/TargetSubtargetInfo.h"
#include <memory>
#include <string>

#define GET_SUBTARGETINFO_HEADER
#include "C166GenSubtargetInfo.inc"

namespace llvm {

class StringRef;
class TargetMachine;

class C166Subtarget : public C166GenSubtargetInfo {
  virtual void anchor();

  bool HasExtInstr = false;
  bool HasMAC = false;
  // Which derivative's special function registers this part has, over the set
  // every map here agrees about.  Nothing in code generation reads these - the
  // compiler names no peripheral of its own - but the assembler and the
  // disassembler do, and the subtarget is where a feature bit lives.
  bool HasSFRXC164 = false;
  bool HasSFRC167 = false;

  C166InstrInfo InstrInfo;
  C166TargetLowering TLInfo;
  C166FrameLowering FrameLowering;
  std::unique_ptr<const SelectionDAGTargetInfo> TSInfo;

public:
  C166Subtarget(const Triple &TT, const std::string &CPU, const std::string &FS,
                const TargetMachine &TM);

  ~C166Subtarget() override;

  C166Subtarget &initializeSubtargetDependencies(StringRef CPU, StringRef FS);

  /// Parses features string setting specified subtarget options.  Definition
  /// of function is auto generated by tblgen.
  void ParseSubtargetFeatures(StringRef CPU, StringRef TuneCPU, StringRef FS);

  bool hasExtInstr() const { return HasExtInstr; }
  bool hasMAC() const { return HasMAC; }
  bool hasSFRXC164() const { return HasSFRXC164; }
  bool hasSFRC167() const { return HasSFRC167; }

  const C166InstrInfo *getInstrInfo() const override { return &InstrInfo; }
  const C166FrameLowering *getFrameLowering() const override {
    return &FrameLowering;
  }
  const C166TargetLowering *getTargetLowering() const override {
    return &TLInfo;
  }
  const C166RegisterInfo *getRegisterInfo() const override {
    return &InstrInfo.getRegisterInfo();
  }

  const SelectionDAGTargetInfo *getSelectionDAGInfo() const override;
};

} // end namespace llvm

#endif
